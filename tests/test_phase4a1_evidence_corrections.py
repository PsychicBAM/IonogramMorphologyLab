def test_morphology_unchanged_smoke():
    # Thin synthetic ridge — ensure RuleEngine still runs; no threshold edits in 4A.1
    frame = np.zeros((128, 200), dtype=float)
    frame[40:42, 20:180] = 100
    seg = segment_frame(frame)
    feats = extract_features(frame, seg)
    res = RuleEngine().evaluate(feats.values, quality_status="valid")
    assert res.candidate_morphology is not None


