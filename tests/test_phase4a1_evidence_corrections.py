def test_signal_contract_schema_no_mixed_shape_notes():
    data = load_signal_contracts()
    errs = validate_contract_schema(data)
    assert not errs, errs
    amp = next(c for c in data["contracts"] if c["variable_name"] == "Amp_all")
    assert "accepted_shapes" in amp
    assert all(isinstance(s, list) for s in amp["accepted_shapes"])
    assert "accepted_shape_variants" not in amp
    assert amp["optional_presence"] is False
    assert isinstance(amp["verification_evidence"], list)


