def test_formula_summary_computed_not_hand_copied():
    data = load_formula_registry()
    assert data.get("summary_source") == "computed_from_classification"
    items = data["items"]
    assert data["summary"] == compute_formula_summary(items)
    for key in SUMMARY_GROUP_KEYS:
        assert key in data["summary"]
    # Instrument conversions must NOT sit under exact_physical_formulas
    exact = set(data["summary"]["exact_physical_formulas"])
    assert "HEUR_BIN_TO_MHZ" not in exact
    assert "HEUR_BIN_TO_NOMINAL_HEIGHT" not in exact
    assert "HEUR_BIN_TO_MHZ" in data["summary"]["instrument_specific_procedures"]
    assert exact == {"F001"}
    assert "F002" not in exact
    assert data["summary"]["observational_definitions"] == ["F002"]
    assert "F003" in data["summary"]["instrument_specific_procedures"]
    assert "F004" in data["summary"]["morphology_definitions"]
    counts = {k: len(v) for k, v in data["summary"].items()}
    assert counts["exact_physical_formulas"] == 1
    assert counts["observational_definitions"] == 1
    assert counts["exact_signal_processing_formulas"] == 0
    assert counts["instrument_specific_procedures"] == 3
    assert counts["morphology_definitions"] == 4
    assert counts["project_engineering_heuristics"] == 1
    assert counts["unsupported_or_disabled"] == 3


def test_f004_and_defs_have_precise_source_location():
    for fid in ("F004", "DEF_FREQUENCY_SPREAD", "DEF_RANGE_SPREAD", "DEF_MIXED_SPREAD"):
        item = get_formula(fid)
        loc = item.get("source_location") or {}
        assert any(
            loc.get(k) not in (None, "")
            for k in ("printed_page", "pdf_page", "section", "figure", "table", "equation")
        ), fid
        assert item.get("expression_kind") in {
            "exact_quotation",
            "translated_quotation",
            "close_paraphrase",
            "project_interpretation",
        }
        page = (item.get("exact_page_or_equation") or "").lower()
        assert "operational morphology classes" not in page
        assert "pages unknown" not in page


